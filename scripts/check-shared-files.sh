#!/usr/bin/env bash
#
# The four canonical shared docs files must be byte-identical to lfr-tunnel's.
#
# The copy of record is lfr-tunnel `master`. Changes are made there and copied
# here unchanged; a local edit is how the three sites drift apart, which is the
# condition this exists to remove rather than to detect late. See #1329.
#
# Failure modes are deliberately not uniform:
#
#   mismatch   fail. The copies have diverged, which is the whole subject.
#   HTTP 404   fail. A renamed path, a private repo or a changed default
#              branch. It will not fix itself, and treating it as an outage
#              would make this check permanently green while comparing
#              nothing - the exact shape the docs checks here exist to avoid.
#   transport  warn. DNS, a timeout, a 5xx. Real outages happen and should not
#              block an unrelated documentation pull request.
#
# The warning path is the dangerous one, so it says plainly that nothing was
# compared, and names the file it skipped.
set -uo pipefail

RAW="https://raw.githubusercontent.com/peterrichards-lr/lfr-tunnel/master"
FILES=(
    "docs/assets/stylesheets/liferay-blue.css"
    "scripts/mkdocs_github_alerts.py"
    "overrides/main.html"
    "overrides/partials/copyright.html"
)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

fail=0
warned=0
checked=0

for path in "${FILES[@]}"; do
    if [ ! -f "$path" ]; then
        echo "[MISSING-LOCALLY] $path is listed as canonical but is not in this repo."
        fail=1
        continue
    fi

    out="$tmp/$(echo "$path" | tr '/' '_')"
    code=$(curl -sS -w '%{http_code}' -o "$out" --max-time 20 "$RAW/$path" 2>"$tmp/err" || echo "000")

    case "$code" in
        200)
            checked=$((checked + 1))
            if ! cmp -s "$path" "$out"; then
                echo "[SHARED-FILE-DRIFT] $path differs from the canonical copy."
                echo "  Canonical: $RAW/$path"
                echo "  Do not edit this file here. Change it in lfr-tunnel and copy it back."
                diff -u "$path" "$out" | head -20 | sed 's/^/    /'
                fail=1
            fi
            ;;
        404)
            echo "[CANONICAL-FILE-GONE] $RAW/$path returned 404."
            echo "  A renamed path, a private repository or a changed default branch."
            echo "  Failing rather than warning: this does not resolve on its own, and a"
            echo "  silent skip would leave this check green while comparing nothing."
            fail=1
            ;;
        *)
            echo "[SYNC-CHECK-SKIPPED] could not fetch $path (HTTP ${code}). NOTHING WAS COMPARED."
            [ -s "$tmp/err" ] && sed 's/^/    /' "$tmp/err"
            warned=1
            ;;
    esac
done

if [ "$fail" -ne 0 ]; then
    echo
    echo "The shared files have drifted from lfr-tunnel master."
    exit 1
fi

if [ "$warned" -ne 0 ]; then
    echo
    echo "WARNING: the canonical copies could not be reached, so ${checked} of ${#FILES[@]}"
    echo "file(s) were compared. This run proves nothing about the others."
    exit 0
fi

echo "${checked} shared file(s) byte-identical to lfr-tunnel master."
